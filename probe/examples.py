"""Pick example traces by fixed, documented rules (no hand-picking), write
results/examples.json (for the strip figure) and docs/examples.md (full traces).

Rules, applied in order on the primary model:
 1. low-resource math item where L2-forced is wrong and En-forced is right (first by id)
 2. low-resource math item where L2-forced is right and En-forced is wrong (first by id)
 3. the L2-forced trace with the highest repetition score (doomloop candidate)
 4. the first Canadian-French (fr-CA) PIQA item, both arms
 5. the L2-forced trace with the lowest target-language share among non-English prompts
"""
from __future__ import annotations

import argparse
import csv
import json
import os

from probe.langs import LANGS
from probe.metrics import split_trace


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--traces", nargs="+", required=True)
    ap.add_argument("--model", default="tiny-aya-global-q4km")
    ap.add_argument("--out-md", default="docs/examples.md")
    a = ap.parse_args()
    rows = [r for r in csv.DictReader(open(os.path.join(a.results, "per_trace.csv"), encoding="utf-8"))
            if r["model"] == a.model]
    raw = {}
    for p in a.traces:
        for l in open(p, encoding="utf-8"):
            r = json.loads(l)
            raw[(r["arm"], r["id"])] = r
    R = {(r["arm"], r["id"]): r for r in rows}
    low = ("sw", "yo", "zu")
    ids = sorted({r["id"] for r in rows})
    picks = []

    def add(rule, item_id, arms=("l2", "en")):
        for arm in arms:
            if (arm, item_id) in R and not any(p[1] == arm and p[2] == item_id for p in picks):
                picks.append((rule, arm, item_id))

    def both(item_id):
        return ("l2", item_id) in R and ("en", item_id) in R

    c1 = [i for i in ids if i.startswith("mgsm") and i.split("-")[-1] in low and both(i)
          and R[("l2", i)]["correct"] == "0" and R[("en", i)]["correct"] == "1"]
    if c1:
        add("1: L2 wrong, En right (low-resource math)", c1[0])
    c2 = [i for i in ids if i.startswith("mgsm") and i.split("-")[-1] in low and both(i)
          and R[("l2", i)]["correct"] == "1" and R[("en", i)]["correct"] == "0"]
    if c2:
        add("2: L2 right, En wrong (low-resource math)", c2[0])
    l2rows = [r for r in rows if r["arm"] == "l2" and r["rep4"] != ""]
    if l2rows:
        top = max(l2rows, key=lambda r: (float(r["rep4"]), r["id"]))
        add(f"3: highest repetition L2 trace (rep4={float(top['rep4']):.2f})", top["id"], ("l2",))
    c4 = [i for i in ids if i.startswith("piqa") and i.endswith("-fr-CA") and both(i)]
    if c4:
        add("4: Canadian French PIQA", c4[0])
    nonen = [r for r in rows if r["arm"] == "l2" and r["lang"] != "en" and r["target_share"] != ""]
    if nonen:
        lo = min(nonen, key=lambda r: (float(r["target_share"]), r["id"]))
        add(f"5: L2 trace with lowest prompt-language share ({float(lo['target_share']):.2f})", lo["id"], ("l2",))

    ex, md = [], ["# Example traces (selected by fixed rules)\n",
                  "Generated by [`probe/examples.py`](../probe/examples.py) from the committed traces in "
                  "[`results/traces/`](../results/traces/). The prefilled opener is shown in **bold**; everything after it "
                  "is model output, verbatim (greedy decoding; a rerun would not reproduce it byte-for-byte, see "
                  "[`docs/determinism.md`](determinism.md)).\n"]
    for rule, arm, i in picks:
        r, s = raw[(arm, i)], R[(arm, i)]
        trace, _ = split_trace(r["completion"], think_tags=False)
        label = f"[{rule.split(':')[0]}] {i} · {arm}"
        ex.append(dict(label=label, rule=rule, arm=arm, id=i, trace=trace))
        md.append(f"## {label}\n\n*Rule {rule}.* Gold `{s['gold']}`, predicted `{s['pred'] or '∅'}` "
                  f"({'correct' if s['correct'] == '1' else 'wrong'}); {s['gen_tokens']} tokens; whole-trace LID "
                  f"`{s['trace_lid']}`; prompt-language share {s['target_share'] or 'n/a'}; English share "
                  f"{s['english_share'] or 'n/a'}; rep4 {s['rep4'] or 'n/a'}; cap hit {s['cap_hit']}.\n")
        md.append(f"<details><summary>Prompt ({LANGS[r['lang']]['name']})</summary>\n\n```text\n{r['user_message']}\n```\n</details>\n")
        md.append(f"```text\n**{r['prefill']}**{r['completion']}\n```\n")
    json.dump(ex, open(os.path.join(a.results, "examples.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    open(a.out_md, "w", encoding="utf-8").write("\n".join(md))
    print(f"{len(picks)} example traces -> {a.out_md}")


if __name__ == "__main__":
    main()
